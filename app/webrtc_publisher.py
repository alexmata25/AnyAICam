"""Appliance-side WebRTC publisher: bridges the cloud-hosted P2P signaling
exchange (live_view_p2p.py's offer/ICE/answer routes) to a local MediaMTX
process, which does the actual RTSP-in/WebRTC-out media work. Chosen over
building a custom WebRTC media server, per explicit product direction --
MediaMTX already speaks RTSP (the exact protocol this codebase's cameras
already use) in and WHEP/WebRTC out, as a single static binary with no
appliance-side dependency beyond the binary itself.

This module is a signaling BRIDGE and process/config-sync ONLY -- it never
touches a media byte, and it never receives or exposes a camera's RTSP
credentials to the browser. MediaMTX pulls each camera's RTSP stream
directly (same trust boundary FFmpeg's start_live_stream() already has on
this appliance -- see camera_url_fn below), and only ever emits WebRTC
(no credentials, no RTSP) toward the browser. Both MediaMTX's control API
(default :9997) and its WebRTC HTTP signaling port (default :8889) are
bound to 127.0.0.1 only in the config this module writes -- neither is
ever reachable from the LAN or the internet; only the actual WebRTC
media (UDP/ICE, via webrtcLocalUDPAddress) needs to reach the internet,
and that path carries no credentials or control surface, only the video
track a viewer is already authorized to see.

Protocol details below (WHEP route shapes, MediaMTX config/REST-API field
names) were verified against MediaMTX's own real, current source code
(github.com/bluenviron/mediamtx, v1.21.0: internal/servers/webrtc/
http_server.go, internal/conf/webrtc_ice_server.go, internal/conf/path.go,
internal/api/api.go), and then AGAIN against a real v1.21.0 Linux binary
run in isolation on Ryzen (own directory, own ports, never wired to the
live VMS service, removed afterward) -- see docs/PROJECT_CHECKPOINT.md's
2026-09-17 "MediaMTX real-binary verification" entry for the full
transcript. Confirmed live and real: config API add/delete (200/"ok",
idempotent 404 on a second delete); a real config generated by
render_mediamtx_config() (this exact module's own output, not a hand-
written test config) is accepted and MediaMTX starts and listens on
exactly the configured loopback ports; WHEP POST against a real camera's
RTSP source returns 201 + a relative Location header + a real SDP answer
containing real H264/G711 tracks MediaMTX actually read from the camera
(confirmed via the path's own runtime stats: ready=true, real
inboundBytes counted) and real STUN-discovered candidates (including a
genuine server-reflexive candidate off Ryzen's real public IP) already
baked into the answer, non-trickle, exactly as this module's browser-side
counterpart expects; MediaMTX auto-reaps an abandoned/never-fully-
connected WHEP session on its own (no explicit close call needed, backing
the "rely on natural teardown" design decision below); a camera whose
RTSP source is unreachable fails the WHEP POST with a real HTTP 400 after
~10s (MediaMTX's own sourceOnDemandStartTimeout), not a hang -- already
covered by _handle_pending_signal()/whep_offer()'s generic HTTPError
handling, but see the fix below; two cameras' paths operate completely
independently; MediaMTX being down entirely produces a real connection-
refused (urllib reports it as URLError, already handled). RTSP
credentials were verified never to appear in any WHEP/config-API
response at any point.

One real bug this surfaced, now fixed: MediaMTX's own real ~10s failure
latency for an unreachable camera meant _bridge_tick()'s (previously)
synchronous call into _handle_pending_signal() -> whep_offer() could
block this worker's entire asyncio event loop -- shared by every other
background task in this same process -- for up to 10 seconds per stuck
signal. _bridge_tick() now runs _handle_pending_signal() via
asyncio.to_thread(), the same pattern _refresh_camera_map()/
sync_camera_paths() already used.

Trickle ICE (2026-09-17 redesign, replacing the original non-trickle-
by-design v1): the non-trickle wait -- the browser blocking on its own
full local ICE gathering (up to 2000ms) before ever sending the offer
-- was measured live (real browser, real Ryzen appliance, real
staging, 2026-09-17) to be the single largest cost in the whole P2P
path: 612-1584ms across repeated real runs, already exceeding the real
AWS relay's own real win time (130-975ms) in every run, before the
offer had even been sent. Lowering every other timer in the path
(ANYAICAM_LIVE_P2P_SCAN_SECONDS down to its 500ms floor) did not
change the outcome -- relay kept winning -- confirming the client-side
gathering wait, not appliance polling cadence, was the real
architectural bottleneck.

The fix: live_view_page.py's attemptLiveP2P() now sends the offer
immediately after setLocalDescription() resolves, with zero or few
candidates inline, and trickles each subsequently-gathered candidate
via the existing POST /api/customer/live/sessions/{id}/p2p/ice route
-- previously wired but structurally vestigial (gathering had already
finished by the time an offer went out, so no candidate was ever
trickled after the fact). _forward_client_ice_candidate() below is
what actually bridges each of those into MediaMTX's real PATCH
endpoint now, and is load-bearing for real ICE success, not merely
best-effort robustness. Confirmed live (isolated diagnostic against
the real MediaMTX v1.21.0 binary, 2026-09-17, using a real
candidate-stripped browser-generated offer, not a hand-crafted one):
MediaMTX accepts a candidate-sparse WHEP POST offer without error
(201, a real answer with every one of MediaMTX's own candidates
already baked in -- MediaMTX's OWN answer generation remains non-
trickle regardless of the offer's own candidate count, so there is
nothing to trickle FROM MediaMTX after its one answer; only the
client -> appliance direction benefits from trickling), and correctly
accepts a real trickled candidate via PATCH once formatted as a valid
SDP media-line fragment -- see that function's own docstring for the
exact real bug (a literal, real "m=<mid>" media line, e.g. "m=0",
rejected with a real 400) this surfaced and fixed."""

