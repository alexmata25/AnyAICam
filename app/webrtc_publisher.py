def p2p_source_for(camera_id: str, main_url: str) -> tuple[str, str]:
    """(source URL for MediaMTX, "substream"|"main") for browser WebRTC.

    Every stream the camera advertises (ONVIF profiles, else the
    URL-convention guess) is probed with ffprobe using the camera's own
    credentials, and the codec actually observed is recorded next to the
    advertised one (stream["observed_codec"] vs stream["codec"]) -- ONVIF
    Media v1 cannot express H.265, so its "H264" is not trusted. Selection
    uses only the observed codec: a verified H.264 substream first, else the
    main stream when it is H.264, else the main stream with an actionable
    warning recorded (record["webrtc"]) and logged: P2P cannot play it, and
    the browser falls back to the relay, whose HLS is transcoded to H.264
    by the live encoder (the only approved transcoding path). Camera
    encoding settings are never changed here.

    Re-decided when the camera's main URL changes (re-provisioning), when
    the stored capabilities are due for a re-probe, and after MediaMTX
    rejects an offer for codec reasons (see _revalidate_after_codec_rejection).
    Runs network calls, so only call it off the event loop."""
    cached = _p2p_source_choice.get(camera_id)
    if cached and cached[0] == main_url:
        kind = cached[2] if len(cached) > 2 else ("main" if cached[1] == main_url else "substream")
        return cached[1], kind
    chosen = main_url
    transcode = False
    if P2P_STREAM_PREFERENCE != "main":
        _clean, username, password = camera_capabilities.split_credentials(main_url)
        record = _load_capabilities(camera_id)
        if camera_capabilities.needs_reprobe(record, main_url):
            record = camera_capabilities.discover(main_url, soap_call=_onvif_soap_call(), url_candidates=substream_candidates)
        ordered = camera_capabilities.select_streams(record, "live_p2p")
        ordered += [s for s in record.get("streams") or [] if s not in ordered]
        subs = [s for s in ordered if s.get("role") != "main"]
        main_streams = [s for s in ordered if s.get("role") == "main"]
        observed_at = datetime.now(timezone.utc).isoformat()

        def observe(stream: dict, url: str) -> str | None:
            codec = normalize_codec(_probe_video_codec(url))
            stream["observed_codec"] = normalize_codec(codec)
            stream["verified"] = codec is not None
            stream["observed_at"] = observed_at
            return codec

        source_role, sub_codecs = None, []
        for stream in subs:
            codec = observe(stream, camera_capabilities.with_credentials(stream["uri"], username, password))
            sub_codecs.append(codec)
            if codec in WEBRTC_VIDEO_CODECS:
                chosen, source_role = camera_capabilities.with_credentials(stream["uri"], username, password), "sub"
                break
            if codec is not None:
                logger.info("webrtc_publisher.substream_codec_unsupported camera_id=%s codec=%s", camera_id, codec)
        main_codec = None
        if main_streams:
            main_codec = observe(main_streams[0], main_url)
        elif source_role is None:
            main_codec = normalize_codec(_probe_video_codec(main_url))
        if source_role is None and main_codec in WEBRTC_VIDEO_CODECS:
            source_role = "main"
        incompatible = source_role is None and (main_codec is not None or any(c is not None for c in sub_codecs))
        if incompatible and P2P_TRANSCODE != "off":
            # Transcode the smallest stream that could actually be opened.
            openable = [(s, camera_capabilities.with_credentials(s["uri"], username, password)) for s in subs if s.get("verified")]
            if main_streams and main_streams[0].get("verified") or (not main_streams and main_codec):
                openable.append((main_streams[0] if main_streams else {"width": None}, main_url))
            openable.sort(key=lambda pair: pair[0].get("width") or 10**6)
            if openable:
                chosen, transcode = openable[0][1], True
                source_role = "transcode"
                logger.info("webrtc_publisher.p2p_transcode camera_id=%s from=%s", camera_id,
                            "main" if chosen == main_url else "substream")
        if incompatible and not transcode:
            logger.warning("webrtc_publisher.no_webrtc_compatible_stream camera_id=%s main_codec=%s sub_codecs=%s "
                           "action=set_one_camera_stream_to_h264_or_use_relay", camera_id, main_codec,
                           ",".join(c or "unavailable" for c in sub_codecs) or "none")
        record["webrtc"] = {
            "compatible": not incompatible or transcode,
            "source_role": source_role or "main",
            "transcoded": transcode,
            "main_observed_codec": main_codec,
            "warning": ("No H.264 stream on this camera: WebRTC live view is transcoded to H.264 on the appliance "
                        "(extra CPU). Setting a camera stream to H.264 avoids that." if transcode else
                        "No H.264 stream on this camera: browsers cannot play it over WebRTC. Set the camera's "
                        "substream (or main stream) to H.264, or view it through the relay." if incompatible else None),
            "checked_at": observed_at,
        }
        _save_capabilities(camera_id, record)
    kind = "transcode" if transcode else ("main" if chosen == main_url else "substream")
    _p2p_source_choice[camera_id] = (main_url, chosen, kind)
    logger.info("webrtc_publisher.p2p_source camera_id=%s stream=%s", camera_id, kind)
    return chosen, kind


# camera_id -> monotonic time of the last codec-triggered revalidation.
_codec_revalidated_at: dict = {}
CODEC_REVALIDATE_MIN_SECONDS = 300.0


def _revalidate_after_codec_rejection(camera_id: str) -> bool:
    """MediaMTX refused an offer because the path's codec is not playable by
    the browser: forget the cached choice, mark the stored capabilities due
    for a re-probe, and re-add this camera's path on the next sync (add falls
    back to replace when the path exists). Rate-limited per camera so an
    H.265-only camera cannot cause a probe loop. Returns True if scheduled."""
    global _paths_resync_pending
    now = time.monotonic()
    last = _codec_revalidated_at.get(camera_id)
    if last is not None and now - last < CODEC_REVALIDATE_MIN_SECONDS:
        return False
    _codec_revalidated_at[camera_id] = now
    _p2p_source_choice.pop(camera_id, None)
    record = _load_capabilities(camera_id)
    if isinstance(record, dict):
        record["probed_at"] = "1970-01-01T00:00:00+00:00"
        _save_capabilities(camera_id, record)
    _known_paths.discard(camera_id)
    _paths_resync_pending = True
    logger.info("webrtc_publisher.codec_revalidation_scheduled camera_id=%s", camera_id)
    return True


def sync_camera_paths(camera_url_fn) -> None:
    """Reconciles MediaMTX's configured paths against the current known-
    camera set -- adds a path for every camera not yet configured, removes
    one for every camera no longer known (removed/reassigned since the
    last sync), exactly the same "diff against latest known state" shape
    _reconcile_relay_commands() already uses for live relay activation.
    Path name is the camera's own camera_id (already an opaque, unique
    identifier -- consistent with how S3 key prefixes address cameras
    elsewhere in this codebase), never the camera_number, so a path never
    needs renaming if a camera is moved to a different slot.

    camera_url_fn(camera_number) -> credentialed RTSP URL is injected by
    the caller (main.py's own camera_url()) rather than imported directly
    -- main.py is what imports this module to wire its background task, so
    importing back from main.py would be a circular import; this mirrors
    the same dependency-injection shape already used for
    register_live_playlist_routes(..., local_identity=lambda: ...) in
    main.py's own route registration. The credential is read once here,
    handed straight to MediaMTX's local (loopback-only) config API, and
    never logged, returned, or exposed to any other caller -- MediaMTX
    itself is the only thing that ever opens the RTSP connection."""
    with _lock:
        camera_map = dict(_camera_map)
    desired = set(camera_map)

    for camera_id in _known_paths - desired:
        status, _ = _config_request("DELETE", f"/v3/config/paths/delete/{camera_id}")
        if status in (200, 404):
            _known_paths.discard(camera_id)
        else:
            logger.warning("webrtc_publisher.path_delete_failed camera_id=%s status=%s", camera_id, status)

    for camera_id in set(_path_add_retries) - desired:
        _path_add_retries.pop(camera_id, None)

    for camera_id in desired - _known_paths:
        camera_number = camera_map[camera_id]
        try:
            source = camera_url_fn(camera_number)
        except Exception as error:
            logger.warning("webrtc_publisher.camera_url_unavailable camera_id=%s error=%s", camera_id, error)
            continue
        source, stream_kind = p2p_source_for(camera_id, source)
        path_config = path_config_for(source, stream_kind)
        status, _ = _config_request("POST", f"/v3/config/paths/add/{camera_id}", path_config)
        if status == 0 and _defer_path_add(camera_id):
            # MediaMTX never answered (2026-09-25, Ryzen: a timeout right
            # after a restart). A replace now would most likely wait out the
            # same timeout; the retry first checks MediaMTX's path list, so
            # an add that was applied after all is adopted, not re-posted.
            continue
        if status not in (0, 200, 201):
            # 2026-09-24, confirmed live on Ryzen: under startup load an add
            # can time out HERE after MediaMTX has already created the path,
            # and every later add then fails 400 ("already exists") -- the
            # camera stayed out of _known_paths, so every P2P offer for it
            # was refused as unconfigured until the next restart. replace
            # sets the same config whether or not the path already exists.
            status, _ = _config_request("POST", f"/v3/config/paths/replace/{camera_id}", path_config)
        if status in (200, 201):
            _known_paths.add(camera_id)
            _path_add_retries.pop(camera_id, None)
        else:
            logger.warning("webrtc_publisher.path_add_failed camera_id=%s status=%s", camera_id, status)


# --------------------------------------------------------------- WHEP signaling bridge

def _resolve_location(location: str) -> str:
    """MediaMTX's Location header (WHEP spec) may be a path-absolute
    reference ("/{path}/whep/{secret}") rather than a full URL --
    resolved against MEDIAMTX_WEBRTC_BASE either way."""
    if location.startswith("http://") or location.startswith("https://"):
        return location
    return MEDIAMTX_WEBRTC_BASE + (location if location.startswith("/") else f"/{location}")


def _whep_error_reason(error) -> str:
    """MediaMTX's own rejection reason (its JSON {"error": ...} body), made
    safe to log: RTSP URLs, ICE credentials, fingerprints, candidates and
    any SDP are removed, and the text is capped."""
    try:
        body = error.read(2048).decode("utf-8", errors="replace")
    except Exception:
        return "unavailable"
    try:
        parsed = json.loads(body)
        if isinstance(parsed, dict) and isinstance(parsed.get("error"), str):
            body = parsed["error"]
    except ValueError:
        pass
    body = re.sub(r"rtsps?://\S*", "<rtsp-url>", body)
    body = re.sub(r"fingerprint[:=]\s*\S+(\s+[0-9A-Fa-f]{2}(:[0-9A-Fa-f]{2})*)?", "fingerprint:<redacted>", body, flags=re.IGNORECASE)
    body = re.sub(r"(ice-pwd|ice-ufrag)[:=]\s*\S+", r"\1:<redacted>", body, flags=re.IGNORECASE)
    body = re.sub(r"candidate:[^\r\n\"]*?\btyp\s+\S+", "candidate:<redacted>", body)
    body = re.sub(r"candidate:\S+", "candidate:<redacted>", body)
    body = re.sub(r"\b(?:\d{1,3}\.){3}\d{1,3}\b", "<ip>", body)
    body = re.sub(r"v=0.*", "<sdp-redacted>", body, flags=re.DOTALL)
    return " ".join(body.split())[:200] or "empty"


def whep_offer(path_name: str, sdp_offer: str) -> tuple[str, str] | None:
    """POSTs a complete (non-trickle -- see module docstring) SDP offer to
    MediaMTX's local WHEP endpoint for one camera's path. Returns
    (session_location, sdp_answer) on success, None on any failure
    (MediaMTX unreachable, path not found/no source, invalid SDP) -- the
    caller treats None exactly like "P2P isn't available for this
    session right now", which the browser's own bounded timeout already
    turns into a relay fallback with zero special-casing needed here."""
    request = urllib.request.Request(
        f"{MEDIAMTX_WEBRTC_BASE}/{path_name}/whep",
        data=sdp_offer.encode(), method="POST",
        headers={"Content-Type": "application/sdp"},
    )
    try:
        with urllib.request.urlopen(request, timeout=10) as response:
            location = response.headers.get("Location")
            answer_sdp = response.read().decode()
            if not location or not answer_sdp.strip():
                logger.warning("webrtc_publisher.whep_offer_malformed_response path=%s", path_name)
                return None
            return _resolve_location(location), answer_sdp
    except urllib.error.HTTPError as error:
        reason = _whep_error_reason(error)
        logger.warning("webrtc_publisher.whep_offer_rejected path=%s status=%s reason=%s", path_name, error.code, reason)
        if error.code == 400 and "codec" in reason.lower():
            _revalidate_after_codec_rejection(path_name)
        return None
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        logger.warning("webrtc_publisher.whep_offer_unreachable path=%s error=%s", path_name, error)
        return None


def _forward_client_ice_candidate(session_location: str, candidate: dict) -> None:
    """Trickle ICE (2026-09-17): forwards one browser-gathered ICE
    candidate to MediaMTX's real WHEP PATCH endpoint as it arrives --
    load-bearing now that the browser sends its offer immediately after
    setLocalDescription() rather than waiting for its own local ICE
    gathering to finish first (see live_view_page.py's own P2P JS and
    this module's docstring for why: that wait alone, confirmed live,
    cost 600-1500ms client-side and was the single largest reason relay
    consistently won the P2P-vs-relay race even after every other
    timer in this path was already at its floor).

    media_line MUST be a real, valid SDP media line -- confirmed live
    against the real MediaMTX v1.21.0 binary (isolated diagnostic,
    2026-09-17) that "m=<mid>" (e.g. "m=0", this function's own
    previous, never-actually-exercised output) is rejected outright
    with a real 400 "sdp: invalid port value" error; "m=video 9
    UDP/TLS/RTP/SAVPF 0" (the standard RFC 8840 trickle-ice-sdpfrag
    placeholder shape -- port 9 is the conventional "discard" port for
    a fragment that isn't renegotiating media itself) is accepted
    (204), confirmed with the same real binary. Hardcoded to video
    because this whole system only ever creates exactly one recvonly
    video transceiver (live_view_page.py's attemptLiveP2P():
    pc.addTransceiver('video', {direction: 'recvonly'})) -- sdpMid is
    always "0" for that single m-line in practice, but the media type
    itself, not just the mid, must match what MediaMTX's parser expects
    for the line to be valid at all.

    Best-effort: a failure here never surfaces anywhere (this is now
    one candidate among possibly several a session needs, not the only
    chance at connectivity -- ICE can still succeed with a subset)."""
    candidate_line = str(candidate.get("candidate", "")).strip()
    if not candidate_line:
        return
    mid = candidate.get("sdpMid") if isinstance(candidate.get("sdpMid"), str) and candidate.get("sdpMid") else "0"
    fragment = f"m=video 9 UDP/TLS/RTP/SAVPF 0\r\na=mid:{mid}\r\na={candidate_line}\r\n"
    request = urllib.request.Request(
        session_location, data=fragment.encode(), method="PATCH",
        headers={"Content-Type": "application/trickle-ice-sdpfrag"},
    )
    try:
        urllib.request.urlopen(request, timeout=5).close()
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError, OSError) as error:
        logger.info("webrtc_publisher.ice_forward_failed error=%s", error)


def _handle_pending_signal(camera_url_fn, item: dict) -> None:
    session_id = item.get("session_id")
    camera_id = item.get("camera_id")
    kind = item.get("kind")
    payload = item.get("payload") or {}
    if not isinstance(session_id, str) or not isinstance(camera_id, str):
        return

    if kind == "offer":
        sdp = str(payload.get("sdp", ""))
        if not sdp.strip():
            return
        with _lock:
            path_configured = camera_id in _known_paths
        if not path_configured:
            logger.info("webrtc_publisher.offer_for_unconfigured_camera camera_id=%s", camera_id)
            return
        result = whep_offer(camera_id, sdp)
        if result is None:
            return
        location, answer_sdp = result
        _whep_sessions[session_id] = location
        _control_plane_post(f"/api/appliance/live/{camera_id}/p2p/answer", {"session_id": session_id, "sdp": answer_sdp})
    elif kind == "ice_client":
        location = _whep_sessions.get(session_id)
        if location:
            _forward_client_ice_candidate(location, payload)
        # No location yet (offer not processed first, or already failed) --
        # dropped, matching _forward_client_ice_candidate()'s own
        # best-effort contract.


def _pending_poll_request() -> tuple[str, float]:
    """(path, HTTP timeout) for one pending-signal poll -- a long-poll when
    LONG_POLL_SECONDS > 0 (see its comment), else the original plain poll."""
    if LONG_POLL_SECONDS > 0:
        return f"/api/appliance/live/p2p/pending?wait={LONG_POLL_SECONDS:g}", LONG_POLL_HTTP_TIMEOUT_SECONDS
    return "/api/appliance/live/p2p/pending", 10.0


def _delay_after_poll(long_poll_honored: bool) -> float:
    """Seconds to wait before the next poll: none after a poll the cloud
    actually held open (it already waited), SCAN_SECONDS otherwise -- a
    failed/unreachable poll, or an older cloud that ignores ?wait=."""
    return 0.0 if long_poll_honored else SCAN_SECONDS


async def _bridge_tick(camera_url_fn) -> bool:
    """Every blocking call in here (the control-plane poll itself, and
    each pending signal's own MediaMTX HTTP round trip) runs via
    asyncio.to_thread() -- confirmed live against the real MediaMTX
    binary that an unreachable camera's WHEP POST can legitimately take
    up to MediaMTX's own ~10s sourceOnDemandStartTimeout before failing
    (see module docstring), and this worker's event loop is shared with
    every other background task in this process; a single stuck signal
    must never stall the rest of them.

    Returns True when the cloud honored a long-poll (echoed
    long_poll_seconds), so the worker can re-poll without sleeping."""
    path, timeout = _pending_poll_request()
    response = await asyncio.to_thread(_control_plane_get, path, timeout)
    if not isinstance(response, dict):
        return False
    long_poll_honored = LONG_POLL_SECONDS > 0 and bool(response.get("long_poll_seconds"))
    pending = response.get("pending")
    if not isinstance(pending, list):
        return long_poll_honored
    for item in pending:
        if isinstance(item, dict):
            await asyncio.to_thread(_handle_pending_signal, camera_url_fn, item)
    return long_poll_honored


async def webrtc_publisher_worker(camera_url_fn) -> None:
    """Top-level background task -- mirrors live_relay_uploader.live_relay_
    worker()'s own shape (role/flag gate, sleep-forever when disabled,
    scan-and-sleep loop when enabled, exceptions logged and retried next
    cycle, never crash the process). Disabled by ANYAICAM_LIVE_P2P_ENABLED
    defaulting false -- this task does nothing (not even spawn MediaMTX)
    until that flag is explicitly set, matching the same fail-closed
    default every other opt-in worker in this codebase already uses."""
    if RUNTIME_ROLE not in {"edge", "combined"} or not LIVE_P2P_ENABLED:
        webrtc_publisher_state["worker_status"] = "disabled"
        while True:
            await asyncio.sleep(3600)

    webrtc_publisher_state["worker_status"] = "running"
    logger.info("webrtc_publisher.worker_started")
    # -inf, not 0.0: time.monotonic() counts from boot, so 0.0 delayed the
    # first refresh (the first path sync) until CONFIG_REFRESH_SECONDS of uptime.
    last_config_refresh = float("-inf")
    try:
        while True:
            long_poll_honored = False
            try:
                _ensure_mediamtx_running()
                now = time.monotonic()
                if now - last_config_refresh >= CONFIG_REFRESH_SECONDS:
                    await asyncio.to_thread(_refresh_camera_map)
                    await asyncio.to_thread(reconcile_camera_paths, camera_url_fn)
                    await asyncio.to_thread(sync_additional_hosts)
                    last_config_refresh = now
                elif _paths_resync_pending or _path_add_retry_due():
                    # MediaMTX was just restarted, or an unanswered path add
                    # is due again: do it now, not at the next
                    # CONFIG_REFRESH_SECONDS.
                    await asyncio.to_thread(reconcile_camera_paths, camera_url_fn)
                long_poll_honored = bool(await _bridge_tick(camera_url_fn))
                webrtc_publisher_state["last_scan_at"] = time.time()
                webrtc_publisher_state["last_error"] = None
            except asyncio.CancelledError:
                raise
            except Exception as error:
                webrtc_publisher_state["last_error"] = str(error)
                logger.warning("webrtc_publisher.worker_iteration_failed error=%s", error)
            # A long-poll that the cloud actually held open already waited;
            # yield to the loop and poll again straight away.
            await asyncio.sleep(_delay_after_poll(long_poll_honored))
    finally:
        stop_mediamtx()
