def _config_request(method: str, path: str, payload: dict | None = None) -> tuple[int, str]:
    """Talks to MediaMTX's own local config REST API (never the cloud
    control plane) -- returns (status_code, body_text); never raises, a
    status of 0 means the request itself failed (MediaMTX unreachable)."""
    data = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(MEDIAMTX_API_BASE + path, data=data, method=method,
                                      headers={"Content-Type": "application/json"} if data is not None else {})
    try:
        with urllib.request.urlopen(request, timeout=MEDIAMTX_API_TIMEOUT_SECONDS) as response:
            return response.status, response.read().decode()
    except urllib.error.HTTPError as error:
        return error.code, error.read().decode() if error.fp else ""
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        logger.warning("webrtc_publisher.mediamtx_api_unreachable path=%s error=%s", path, error)
        return 0, str(error)


def _wait_for_mediamtx_api(timeout_seconds: float) -> bool:
    """True once MediaMTX's config API answers (a new process needs a
    moment before it accepts path adds); False after timeout_seconds."""
    deadline = time.monotonic() + timeout_seconds
    while True:
        status, _ = _config_request("GET", "/v3/config/global/get")
        if status == 200:
            return True
        if time.monotonic() >= deadline:
            return False
        time.sleep(0.5)


def _mediamtx_path_names() -> set[str] | None:
    """Every path MediaMTX currently has configured (GET
    /v3/config/paths/list, paginated), or None when it cannot be read."""
    names: set[str] = set()
    page = 0
    while True:
        status, body = _config_request("GET", f"/v3/config/paths/list?itemsPerPage=1000&page={page}")
        if status != 200:
            return None
        try:
            data = json.loads(body)
            names.update(str(item.get("name")) for item in data.get("items") or [] if isinstance(item, dict))
            page_count = int(data.get("pageCount") or 1)
        except (ValueError, TypeError, AttributeError):
            return None
        page += 1
        if page >= page_count or page >= 100:
            return names


def _forget_paths_mediamtx_lost() -> None:
    """Drops from _known_paths any camera MediaMTX no longer actually has
    (a restart this process did not observe, a config reload), so the next
    sync re-adds just those. One read-only GET per config refresh; while
    the two agree nothing is re-added, and an unreadable list changes
    nothing.

    A camera whose add is awaiting a retry but that MediaMTX already has
    (the unanswered add was applied after our timeout) is adopted here,
    with no second POST."""
    actual = _mediamtx_path_names()
    if actual is None:
        return
    adopted = set(_path_add_retries) & actual
    with _lock:
        lost = _known_paths - actual
        _known_paths.difference_update(lost)
        _known_paths.update(adopted)
    for camera_id in adopted:
        _path_add_retries.pop(camera_id, None)
        logger.info("webrtc_publisher.path_add_confirmed camera_id=%s", camera_id)
    if lost:
        logger.warning("webrtc_publisher.paths_missing_in_mediamtx count=%s", len(lost))


def _path_add_retry_due() -> bool:
    now = time.monotonic()
    return any(due <= now for _attempts, due in _path_add_retries.values())


def _defer_path_add(camera_id: str) -> bool:
    """Schedules another attempt for an add MediaMTX did not answer. False
    once PATH_ADD_MAX_ATTEMPTS are used up: the caller then logs the
    failure and the next config refresh starts over, as before."""
    attempts = _path_add_retries.get(camera_id, (0, 0.0))[0] + 1
    if attempts >= PATH_ADD_MAX_ATTEMPTS:
        _path_add_retries.pop(camera_id, None)
        return False
    delay = PATH_ADD_RETRY_BASE_SECONDS * min(2 ** (attempts - 1), 8)
    _path_add_retries[camera_id] = (attempts, time.monotonic() + delay)
    logger.info("webrtc_publisher.path_add_retry_scheduled camera_id=%s attempt=%s retry_in=%.1fs", camera_id, attempts, delay)
    return True


def reconcile_camera_paths(camera_url_fn) -> None:
    """sync_camera_paths() against what MediaMTX really has. After a
    MediaMTX (re)start it waits for the new process's API, then re-adds
    every camera; a still-starting MediaMTX leaves the resync pending for
    the worker's next iteration."""
    global _paths_resync_pending
    if _paths_resync_pending:
        if not _wait_for_mediamtx_api(MEDIAMTX_STARTUP_GRACE_SECONDS):
            return
        _paths_resync_pending = False
        logger.info("webrtc_publisher.paths_resync_after_mediamtx_start")
    else:
        _forget_paths_mediamtx_lost()
    sync_camera_paths(camera_url_fn)


def substream_candidates(main_url: str) -> list[str]:
    """Lower-bitrate sibling URLs for a camera's main RTSP stream, derived
    only from widely used, vendor-neutral URL conventions -- never from a
    camera number or a hardcoded camera:
      .../Channels/<n>01 (+ profile=Profile_1)  ->  .../Channels/<n>02 (+ profile=Profile_2)
      ...subtype=0                              ->  ...subtype=1
    An unrecognized URL yields no candidate (the main stream is used)."""
    import re
    candidates = []
    hik = re.sub(r"(/[Cc]hannels/)(\d*)01(?=[/?]|$)", r"\g<1>\g<2>02", main_url, count=1)
    if hik != main_url:
        hik = re.sub(r"([?&]profile=)Profile_1(?![0-9])", r"\g<1>Profile_2", hik)
        candidates.append(hik)
    dahua = re.sub(r"([?&]subtype=)0(?![0-9])", r"\g<1>1", main_url, count=1)
    if dahua != main_url:
        candidates.append(dahua)
    return candidates


# Codecs a browser can receive over WebRTC from MediaMTX (ffprobe codec_name).
# Measured on the real stream, never taken from ONVIF metadata: ONVIF Media
# (v1) cannot express H.265, so a camera whose substream is set to H.265 can
# still report "H264" in GetProfiles (seen live 2026-10-10: MediaMTX answered
# "codecs not supported by client" for a substream ONVIF called H264).
WEBRTC_VIDEO_CODECS = frozenset({"h264"})
_CODEC_ALIASES = {"avc": "h264", "avc1": "h264", "hevc": "h265", "hev1": "h265", "hvc1": "h265"}


def normalize_codec(value) -> str | None:
    """One spelling for observed codecs, shared with the camera-lifecycle
    work (stream_codec / onvif_media._codec_name): lower-case, "h264" and
    "h265" (hevc/hev1/hvc1), anything else lower-cased, empty -> None."""
    text = str(value or "").strip().lower()
    return _CODEC_ALIASES.get(text, text) or None

# On-demand H.265 -> H.264 transcoding for WebRTC (2026-10-10), used only when
# no camera stream is H.264. "auto" (default) enables it; "off" disables it
# (P2P then keeps the main stream and records the compatibility warning).
P2P_TRANSCODE = os.environ.get("ANYAICAM_LIVE_P2P_TRANSCODE", "auto").strip().lower()
P2P_TRANSCODE_MAX_WIDTH = max(320, int(os.environ.get("ANYAICAM_LIVE_P2P_TRANSCODE_MAX_WIDTH", "1280")))
P2P_TRANSCODE_FPS = max(5, min(30, int(os.environ.get("ANYAICAM_LIVE_P2P_TRANSCODE_FPS", "15"))))
P2P_TRANSCODE_KBPS = max(200, min(4000, int(os.environ.get("ANYAICAM_LIVE_P2P_TRANSCODE_KBPS", "1000"))))
MEDIAMTX_RTSP_LOOPBACK = "rtsp://127.0.0.1:8554"


def transcode_command(source_url: str) -> str:
    """The runOnDemand command MediaMTX starts when the first WebRTC viewer
    asks for a transcoded path and stops runOnDemandCloseAfter after the last
    one leaves: decode the camera stream (substream preferred by the caller),
    re-encode video only to browser-safe H.264 (baseline, no B-frames,
    yuv420p, short GOP, capped width/fps/bitrate) and publish it back into
    the same path over loopback RTSP. Recording and live HLS never use this.
    Every argument is shell-quoted; $MTX_PATH is expanded by MediaMTX."""
    import shlex
    video_filter = f"scale=w=min(iw\\,{P2P_TRANSCODE_MAX_WIDTH}):h=-2,fps={P2P_TRANSCODE_FPS}"
    args = ["ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error",
            "-rtsp_transport", "tcp", "-i", source_url,
            "-an", "-vf", video_filter,
            "-c:v", "libx264", "-preset", "ultrafast", "-tune", "zerolatency",
            "-profile:v", "baseline", "-pix_fmt", "yuv420p", "-bf", "0", "-g", str(P2P_TRANSCODE_FPS * 2),
            "-b:v", f"{P2P_TRANSCODE_KBPS}k", "-maxrate", f"{int(P2P_TRANSCODE_KBPS * 1.2)}k",
            "-bufsize", f"{P2P_TRANSCODE_KBPS * 2}k",
            "-f", "rtsp", "-rtsp_transport", "tcp"]
    return " ".join(shlex.quote(a) for a in args) + f" {MEDIAMTX_RTSP_LOOPBACK}/$MTX_PATH"


def path_config_for(source_url: str, kind: str) -> dict:
    """MediaMTX path config for one camera: a direct on-demand RTSP source,
    or (kind "transcode") a publisher path fed by transcode_command()."""
    if kind == "transcode":
        return {"source": "publisher", "runOnDemand": transcode_command(source_url),
                "runOnDemandRestart": True, "runOnDemandStartTimeout": "15s", "runOnDemandCloseAfter": "10s"}
    return {"source": source_url, "sourceOnDemand": True}


def _probe_video_codec(url: str) -> str | None:
    """The actual codec of the URL's first real video stream as ffprobe
    names it ("h264", "hevc", ...), or None when the stream cannot be
    opened or has no video. Never logs or returns the (credentialed) URL."""
    try:
        result = subprocess.run(
            ["ffprobe", "-v", "error", "-rtsp_transport", "tcp", "-select_streams", "v:0",
             "-show_entries", "stream=codec_type,codec_name,width,height", "-of", "json", url],
            capture_output=True, text=True, timeout=P2P_SUBSTREAM_PROBE_TIMEOUT_SECONDS, check=False,
        )
        if result.returncode != 0:
            return None
        for stream in json.loads(result.stdout or "{}").get("streams") or []:
            if stream.get("codec_type") == "video" and (stream.get("width") or 0) > 0:
                return normalize_codec(stream.get("codec_name"))
        return None
    except (OSError, subprocess.SubprocessError, ValueError):
        return None


